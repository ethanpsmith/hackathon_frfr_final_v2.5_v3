import {readFileSync} from 'node:fs';
import {resolve} from 'node:path';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const root=resolve(import.meta.dirname,'dist');
const source=readFileSync(resolve(root,'telemetry.js'),'utf8').replaceAll('export ','');
const dom={createElement(tag){return element(tag);},createElementNS(ns,tag){return element(tag);}};
function element(tag){return {tag,children:[],attrs:{},style:{setProperty(){}},textContent:'',append(...x){this.children.push(...x);},setAttribute(k,v){this.attrs[k]=v;}};}
const context=vm.createContext({document:dom,Math,Number});
vm.runInContext(source,context);
assert.equal(vm.runInContext('graphDefinitions.length',context),6);
const archive=JSON.parse(readFileSync(resolve(root,'data/archive.json'),'utf8'));
assert.ok(['OUTBOUND','TARGET_LANDED','RETURNING'].every(stage=>archive.frames.some(x=>x.phase===stage)),'replay must show target landing and second climb');
assert.ok(archive.frames.some(x=>x.phase==='TARGET_LANDED'&&Math.abs(x.position.relative_alt)<500));
assert.ok(archive.frames.some(x=>x.phase==='RETURNING'&&x.position.relative_alt>10000));
const frame=archive.frames.find(x=>x.position&&x.position.hdg<36000&&x.battery?.battery_remaining>=0&&x.battery.current_battery>=0&&x.battery.voltage_battery>0&&x.attitude&&x.heartbeat&&x.gps);
assert.ok(frame,'recorded SITL needs position, battery and attitude samples');
context.t={GLOBAL_POSITION_INT:frame.position,SYS_STATUS:frame.battery,ATTITUDE:frame.attitude,HEARTBEAT:frame.heartbeat,EXTENDED_SYS_STATE:frame.extended,MISSION_CURRENT:frame.mission,GPS_RAW_INT:frame.gps};
const values=vm.runInContext('metricsFrom(t)',context);
for(const id of ['battery','altitude','groundspeed','roll','pitch','heading'])assert.ok(Number.isFinite(values[id]),`missing ${id} telemetry`);
const health=vm.runInContext('diagnosticsFrom(t)',context);
for(const id of ['mode','current','voltage','gpsFix','satellites'])assert.notEqual(health[id],null,`missing ${id} diagnostic`);
assert.equal(health.current,frame.battery.current_battery/100);
assert.equal(health.voltage,frame.battery.voltage_battery/1000);
assert.equal(values.heading,frame.position.hdg/100);
context.host=element('div');vm.runInContext('graphs=new Graphs(host);graphs.append(t)',context);
assert.equal(context.host.children.length,6);
for(const card of context.host.children){assert.notEqual(card.children[0].children[1].textContent,'—');assert.ok(card.children[1].children[4].attrs.d);}
const count=vm.runInContext('graphs.samples.length',context);vm.runInContext('graphs.append(t)',context);assert.equal(vm.runInContext('graphs.samples.length',context),count,'duplicate polling frame must not add a point');
context.wrapA={GLOBAL_POSITION_INT:{wall:1,hdg:35900}};
context.wrapB={GLOBAL_POSITION_INT:{wall:2,hdg:100}};
vm.runInContext('graphs.clear();graphs.append(wrapA);graphs.append(wrapB)',context);
assert.equal((context.host.children.at(-1).children[1].children[4].attrs.d.match(/M/g)||[]).length,2,'heading must not draw across north wrap');
assert.equal(vm.runInContext('metricsFrom({}).roll',context),null,'missing sensor is displayed as unavailable');
const batteries=new Set(archive.frames.map(x=>x.battery?.battery_remaining).filter(x=>x>=0));
const altitudes=new Set(archive.frames.map(x=>x.position?.relative_alt));
assert.ok(batteries.size>2&&altitudes.size>20,'replay graphs must receive changing readings');
context.finished={kind:'geographic',status:'PASS',run:'old-2047',route:{path:[[1,2],[3,4]]}};
context.selectedPath=[[1,2],[3,4]];
assert.equal(vm.runInContext('bridgeRunForSelection(finished,selectedPath,null)',context),null,'a prior completed run must not overwrite replay');
assert.equal(vm.runInContext('bridgeRunForSelection(finished,selectedPath,"old-2047")',context),'old-2047');
context.finished.status='RUNNING';
assert.equal(vm.runInContext('bridgeRunForSelection(finished,selectedPath,null)',context),'old-2047','active matching run should attach');
const html=readFileSync(resolve(root,'index.html'),'utf8');
assert.match(html,/class="side"/);assert.match(html,/class="mapwrap"/);assert.match(html,/id="health-mode"/);assert.match(html,/id="health-heading"/);
assert.doesNotMatch(html,/position-form|scenario-grid|Fly to a position|Flight tests/);
console.log('Flightpath layout, six recorded SITL graphs and health diagnostics passed.');
